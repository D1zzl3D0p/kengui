#!/usr/bin/env node
/**
 * Build-time contract generation for the kenkui HTTP API.
 *
 * Runs the pinned kenkui's `python -m kenkui.server.openapi` to dump the live
 * FastAPI OpenAPI schema, then feeds it through `openapi-typescript` to produce
 * TypeScript API types. The output lives in `src/api/generated/` which is
 * git-ignored: the contract is a derived build artifact that can never go stale
 * relative to the kenkui version it was generated from. Nothing Python ships in
 * the app bundle -- this script only runs on the build/dev machine.
 *
 * Also captures the API-compatibility version (kenkui's `API_VERSION`) into
 * `generated/meta.ts` so the runtime handshake knows which version the client
 * was built for.
 *
 * Dev: uses the local kenkui checkout at ../kenkui (its venv interpreter).
 * CI: install the pinned kenkui into the active env and set KENKUI_PYTHON=python
 *     (or leave default candidates); the module resolves from the install.
 *
 * Env overrides:
 *   KENKUI_PYTHON  explicit python interpreter to use
 *   KENKUI_SRC     path added to PYTHONPATH (default ../kenkui/src)
 */
import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const scriptDir = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(scriptDir, '..');
const kenkuiSrc = process.env.KENKUI_SRC
  ? resolve(process.env.KENKUI_SRC)
  : resolve(repoRoot, '..', 'kenkui', 'src');
const outDir = resolve(repoRoot, 'src', 'api', 'generated');

function pythonCandidates() {
  if (process.env.KENKUI_PYTHON) return [process.env.KENKUI_PYTHON];
  return [
    resolve(repoRoot, '..', 'kenkui', '.venv', 'bin', 'python'),
    'python3',
    'python',
  ];
}

function runPython(candidate, args) {
  return execFileSync(candidate, args, {
    env: { ...process.env, PYTHONPATH: `${kenkuiSrc}${process.env.PYTHONPATH ? `:${process.env.PYTHONPATH}` : ''}` },
    encoding: 'utf8',
    maxBuffer: 32 * 1024 * 1024,
  });
}

function firstWorkingPython() {
  let lastError;
  for (const candidate of pythonCandidates()) {
    try {
      runPython(candidate, ['-c', 'import kenkui.server.openapi']);
      return candidate;
    } catch (error) {
      lastError = error;
    }
  }
  throw new Error(
    `Could not find a python interpreter with kenkui importable. Tried: ${pythonCandidates().join(', ')}.\n` +
      `Set KENKUI_PYTHON / KENKUI_SRC. Last error: ${lastError?.message ?? 'unknown'}`
  );
}

async function main() {
  const python = firstWorkingPython();
  console.log(`[contract] using python: ${python}`);

  const openapiJson = runPython(python, ['-m', 'kenkui.server.openapi']);
  const apiVersion = runPython(python, [
    '-c',
    'from kenkui.services.application_service import API_VERSION, SERVICE_VERSION; print(API_VERSION); print(SERVICE_VERSION)',
  ])
    .trim()
    .split('\n');
  const builtForApiVersion = apiVersion[0]?.trim() ?? 'unknown';
  const builtForServerVersion = apiVersion[1]?.trim() ?? 'unknown';

  mkdirSync(outDir, { recursive: true });
  const schemaPath = resolve(outDir, 'openapi.json');
  writeFileSync(schemaPath, openapiJson);

  const { default: openapiTS, astToString } = await import('openapi-typescript');
  const ast = await openapiTS(JSON.parse(openapiJson));
  const dts = `/* eslint-disable */\n/* Generated by scripts/generate-contract.mjs -- DO NOT EDIT. Not committed. */\n${astToString(ast)}`;
  writeFileSync(resolve(outDir, 'openapi.d.ts'), dts);

  const meta = `/* Generated by scripts/generate-contract.mjs -- DO NOT EDIT. Not committed. */
export const BUILT_FOR_API_VERSION = ${JSON.stringify(builtForApiVersion)};
export const BUILT_FOR_SERVER_VERSION = ${JSON.stringify(builtForServerVersion)};
`;
  writeFileSync(resolve(outDir, 'meta.ts'), meta);

  console.log(
    `[contract] generated types (api_version=${builtForApiVersion}, server_version=${builtForServerVersion}) -> ${outDir}`
  );
}

main().catch((error) => {
  console.error(`[contract] generation failed: ${error.message}`);
  process.exit(1);
});
